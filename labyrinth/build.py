import math
import os
import sys

import numpy as np
import yaml

from . import analysis as A
from . import draw, sentiment, text, walk

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# A5 page, text block in mm (see book/labyrinth.sty)
TEXT_W, TEXT_H = 120.0, 177.0
MAZE_H = 170.0     # the full-page maze, leaving room so the page never overflows


def tex_escape(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    s = "".join(rep.get(c, c) for c in s).replace("--", "—")
    # straight double quotes -> curly: opening at the start or after a space, bracket or dash
    out = []
    for k, c in enumerate(s):
        if c == '"':
            out.append("“" if (k == 0 or s[k - 1] in " ([—") else "”")
        else:
            out.append(c)
    return "".join(out)


def fmt(x, nd=2):
    if isinstance(x, (int, np.integer)) or (isinstance(x, float) and x.is_integer() and abs(x) >= 10):
        return f"{int(round(x)):,}".replace(",", "\\,").replace("-", "\u2212")
    return f"{x:.{nd}f}".replace("-", "−")


class Numbers:
    def __init__(self):
        self.lines = []

    def __setitem__(self, k, v):
        self.lines.append("\\expandafter\\def\\csname lab@%s\\endcsname{%s}" % (k, v))

    def write(self, path):
        open(path, "w").write("% generated by labyrinth.build - do not edit\n" + "\n".join(self.lines) + "\n")


def quote(sentence, maxw=28):
    words = sentence.split()
    s = " ".join(words[:maxw]) + (" …" if len(words) > maxw else "")
    # quoted inside double quotes, so the sentence's own quotation marks become single
    return tex_escape(s).replace("“", "‘").replace("”", "’")


def cached_baseline(out, tag, n, t, sc, shuffles, seed):
    """The shuffle baseline, cached on disk; recomputed only when the sentences' lengths,
    turns or the shuffle settings change."""
    import hashlib
    h = hashlib.sha1(np.asarray(n).tobytes() + np.asarray(t).tobytes() + f"{shuffles}:{seed}".encode()).hexdigest()[:16]
    path = os.path.join(out, f"baseline-{tag}-{h}.npz")
    if os.path.exists(path):
        d = np.load(path)
        return {k: d[k] for k in d.files}
    base = A.shuffle_baseline(n, t, sc, n=shuffles, seed=seed)
    np.savez(path, **base)
    return base


def load_book(cfg):
    kw = {k: cfg[k] for k in ("chapter_pattern", "skip_until", "first_chapter", "stop_at") if k in cfg}
    return text.load(cfg["gutenberg"], cfg["title"], cfg["author"], cfg.get("translator", ""), **kw)


def main(cfg_path):
    cfg = yaml.safe_load(open(cfg_path))
    slug = cfg["slug"]
    out = os.path.join(ROOT, "build", slug)
    os.makedirs(out, exist_ok=True)
    book = load_book(cfg)
    S = book.sentences
    n = np.array([len(s.words) for s in S])
    names = sentiment.book_names([s.text for s in S])
    sc = np.array([sentiment.score_text(s.text, names) for s in S], float)
    t = np.array([sentiment.turn(x, cfg.get("dead_zone", 0)) for x in sc])
    w = walk.walk2d(n, t, sc)
    chap = np.array([s.chapter for s in S])
    N = Numbers()
    N["title"] = tex_escape(book.title); N["author"] = tex_escape(book.author)
    N["translator"] = tex_escape(book.translator); N["gid"] = str(book.gid)
    N["sentences"] = fmt(len(S)); N["words"] = fmt(int(n.sum())); N["chapters"] = str(len(book.chapters))

    # ---- robustness: the same tests with ambiguous lexicon words left unscored
    drop = cfg.get("robustness_drop", [])
    if drop:
        sc_r = np.array([sentiment.score_text(s.text, names | frozenset(drop)) for s in S], float)
        t_r = np.array([sentiment.turn(x, cfg.get("dead_zone", 0)) for x in sc_r])
        w_r = walk.walk2d(n, t_r, sc_r)
        m_r = A.global_measures(w_r)
        z_r = A.zscores(m_r, cached_baseline(out, "r", n, t_r, sc_r, cfg.get("shuffles", 200), cfg.get("seed", 7) + 1))
        N["r-words"] = ", ".join(f"\\emph{{{d}}}" for d in drop)
        N["r-handedness"] = fmt(m_r["handedness"], 2)
        N["r-net"] = fmt(int(t_r.sum())); N["net"] = fmt(int(t.sum()))
        for k, v in z_r.items():
            N[f"rz-{k}"] = fmt(v["z"], 1)
        v3r, pitch_r = walk.walk3d(n, t_r, cfg.get("shaft_delta", 0.75))
        N["r-shaft-final"] = fmt(float(v3r[-1, 2]), 0)
        N["r-shaft-final-pitch"] = fmt(float(pitch_r[-1]), 1)
        for k, v in z_r.items():
            N[f"rsig-{k}"] = "1" if abs(v["z"]) >= 3 else "0"
    N["names"] = ", ".join(f"\\emph{{{w}}}" for w in sorted(names))

    # ---- global measures + shuffle baseline
    m = A.global_measures(w)
    base = cached_baseline(out, "m", n, t, sc, cfg.get("shuffles", 200), cfg.get("seed", 7))
    z = A.zscores(m, base)
    for k, v in m.items():
        N[f"m-{k}"] = fmt(v, 3 if abs(v) < 1 else 2)
    for k, v in z.items():
        N[f"z-{k}"] = fmt(v["z"], 1)
        N[f"sig-{k}"] = "1" if abs(v["z"]) >= 3 else "0"
        N[f"b-{k}"] = fmt(v["mean"], 3 if abs(v["mean"]) < 1 else 2)
        N[f"sd-{k}"] = fmt(v["sd"], 3 if abs(v["sd"]) < 1 else 2)
        N[f"p-{k}"] = ("<0.005" if v["p"] < 0.005 else fmt(v["p"], 3))
        nshuf = cfg.get("shuffles", 200)
        N[f"nex-{k}"] = str(int(round(v["p"] * (nshuf + 1) - 1)))   # shuffles at least as extreme as the book
        hist, edges = np.histogram(base[k], bins=24)
        with open(os.path.join(out, f"baseline-{k}.dat"), "w") as f:
            f.write("x y\n")
            for c, a, b in zip(hist, edges[:-1], edges[1:]):
                f.write(f"{(a + b) / 2:.6g} {c}\n")
        N[f"bmin-{k}"] = f"{min(edges[0], v['value']):.6g}"; N[f"bmax-{k}"] = f"{max(edges[-1], v['value']):.6g}"
        N[f"raw-{k}"] = f"{v['value']:.6g}"
    N["shuffles"] = str(len(base["drift"]))
    N["m-share-left-pct"] = fmt(100 * m["share_left"], 1); N["m-share-right-pct"] = fmt(100 * m["share_right"], 1)
    N["m-share-straight-pct"] = fmt(100 * m["share_straight"], 1)
    N["m-handedness-abs"] = fmt(abs(m["handedness"]), 2)

    # transition table: observed vs expected under shuffling (exact expectation = product of marginals)
    lab = {-1: "R", 0: "S", 1: "L"}
    pairs = list(zip(t[:-1], t[1:]))
    for a in (-1, 0, 1):
        for b in (-1, 0, 1):
            obs = sum(1 for p in pairs if p == (a, b))
            exp = (t == a).sum() * (t == b).sum() / len(t) * (len(t) - 1) / len(t)
            N[f"tr-{lab[a]}{lab[b]}"] = fmt(obs); N[f"te-{lab[a]}{lab[b]}"] = fmt(exp, 0)
            N[f"tq-{lab[a]}{lab[b]}"] = fmt(obs / exp, 2)
    # plain language: after a sentence of kind a, how often is the next of the same kind (vs its overall share)
    for a in (-1, 0, 1):
        row = sum(1 for p in pairs if p[0] == a)
        same = sum(1 for p in pairs if p == (a, a))
        N[f"pp-{lab[a]}"] = fmt(100 * same / row, 0)
        N[f"base-{lab[a]}"] = fmt(100 * (t == a).mean(), 0)
        N[f"tqpct-{lab[a]}"] = fmt(100 * (same / row / (t == a).mean() - 1), 0)

    # ---- gyration curve with baseline band
    tt, rg = A.gyration_curve(w, 100)
    rng = np.random.default_rng(11)
    curves = []
    for _ in range(60):
        p = rng.permutation(len(n))
        curves.append(A.gyration_curve(walk.walk2d(n[p], t[p], sc[p]), 100)[1])
    curves = np.array(curves)
    lo, mid, hi = np.percentile(curves, [5, 50, 95], axis=0)
    with open(os.path.join(out, "gyration.dat"), "w") as f:
        f.write("t rg lo mid hi\n")
        for row in zip(tt, rg, lo, mid, hi):
            f.write(" ".join(f"{v:.5g}" for v in row) + "\n")
    half = float(tt[np.argmax(rg >= rg[-1] / 2)])
    N["rg-half"] = fmt(100 * half, 0)
    above = rg > hi
    N["rg-above-pct"] = fmt(100 * above.mean(), 0)

    # ---- local structures
    cr = A.crossings(w)
    ov = A.overlaps(w)
    kn = A.knots(w, cr, cell=cfg.get("knot_cell", 24), k=3)
    hb = A.hub(w, cr)
    rt = A.longest_return(cr)
    co = A.coil(w)
    dk = A.darkest(w)
    cor = A.longest_corridor(w)
    pal = ov[np.argmax(ov[:, 2])] if len(ov) else None
    J = A.chapter_overlap(w, book.chapter_starts)
    Jo = J.copy(); np.fill_diagonal(Jo, 0)
    ci, cj = np.unravel_index(Jo.argmax(), Jo.shape)
    N["share-ch-a"] = str(ci + 1); N["share-ch-b"] = str(cj + 1); N["share-ch-j"] = fmt(100 * Jo.max(), 1)
    inv = np.zeros(len(S))
    for _, _, i, j in cr:
        inv[i] += 1; inv[j] += 1
    for c in range(len(book.chapters)):      # crossings per sentence, chapter by chapter
        N[f"chx-{c + 1}"] = fmt(float(inv[chap == c].mean()), 2)
    gaps = cr[:, 3] - cr[:, 2]
    N["cross-long-pct"] = fmt(100 * (gaps > len(S) / 4).mean(), 0)
    N["cross-short-pct"] = fmt(100 * (gaps <= 50).mean(), 0)

    def ch(i):
        return int(chap[i]) + 1

    def sref(i):
        return f"\\S\\,{i + 1}"

    for k, q in enumerate(kn):
        chs = sorted(set(int(chap[i]) + 1 for i in q["sentences"]))
        comp = {c: sum(1 for i in q["sentences"] if chap[i] + 1 == c) for c in chs}
        top = sorted(comp, key=lambda c: -comp[c])
        q["chapters"] = chs; q["composition"] = comp
        key = "ABC"[k]
        N[f"knot{key}-crossings"] = fmt(q["crossings"]); N[f"knot{key}-first"] = sref(q["first"])
        N[f"knot{key}-last"] = sref(q["last"]); N[f"knot{key}-nsent"] = fmt(len(q["sentences"]))
        N[f"knot{key}-chapters"] = ", ".join(map(str, chs)); N[f"knot{key}-gap"] = fmt(q["gap_median"], 0)
        N[f"knot{key}-top"] = str(top[0]); N[f"knot{key}-topn"] = fmt(comp[top[0]])
        N[f"knot{key}-second"] = str(top[1] if len(top) > 1 else top[0])
        N[f"knot{key}-secondn"] = fmt(comp[top[1]] if len(top) > 1 else 0)
    N["hub-ref"] = sref(hb["i"]); N["hub-n"] = fmt(hb["crossings"]); N["hub-ch"] = str(ch(hb["i"]))
    N["hub-quote"] = quote(S[hb["i"]].text, 40)
    span = [ch(j) for j in hb["crossed_by"]]
    N["hub-span-chapters"] = ", ".join(map(str, sorted(set(span))))
    N["ret-i"] = sref(rt["i"]); N["ret-j"] = sref(rt["j"]); N["ret-gap"] = fmt(rt["gap"])
    N["ret-chi"] = str(ch(rt["i"])); N["ret-chj"] = str(ch(rt["j"]))
    N["ret-qi"] = quote(S[rt["i"]].text); N["ret-qj"] = quote(S[rt["j"]].text)
    N["coil-first"] = sref(co["first"]); N["coil-last"] = sref(co["last"]); N["coil-q"] = fmt(abs(co["quarter_turns"]))
    N["coil-dir"] = "left" if co["quarter_turns"] > 0 else "right"; N["coil-ch"] = str(ch(co["first"]))
    N["coil-quote"] = quote(S[co["first"]].text)
    N["dark-first"] = sref(dk["first"]); N["dark-last"] = sref(dk["last"]); N["dark-score"] = fmt(dk["score"], 0)
    N["dark-ch"] = str(ch(dk["first"])); N["dark-quote"] = quote(S[dk["first"]].text)
    N["cor-first"] = sref(cor["first"]); N["cor-last"] = sref(cor["last"]); N["cor-n"] = fmt(cor["sentences"])
    N["cor-words"] = fmt(cor["words"]); N["cor-ch"] = str(ch(cor["first"])); N["cor-quote"] = quote(S[cor["first"]].text)
    if pal is not None:
        N["pal-i"] = sref(pal[0]); N["pal-j"] = sref(pal[1]); N["pal-len"] = fmt(int(pal[2]))
        N["pal-chi"] = str(ch(pal[0])); N["pal-chj"] = str(ch(pal[1]))
        N["pal-qi"] = quote(S[pal[0]].text); N["pal-qj"] = quote(S[pal[1]].text)
        N["pal-n"] = fmt(len(ov))
    N["first-quote"] = quote(S[0].text, 40); N["last-quote"] = quote(S[-1].text, 40)

    # ---- the maze page: short lettered labels in the margins whose arrows stop before
    #      the drawing; each letter has a magnified cut-out on a separate page
    v = w.vertices()

    def mid(a, b):
        return (v[a] + v[b + 1]) / 2

    def focus_window(ids, rmin=8.0, rmax=15.0):
        """Centre and radius of a cut-out: the point of the feature's own path nearest
        its centroid (never empty space), wide enough to show it, narrow enough to read."""
        pts = np.vstack([v[i] for i in ids] + [v[i + 1] for i in ids]).astype(float)
        c = pts.mean(0)
        best = pts[np.argmin(((pts - c) ** 2).sum(1))]
        half = (pts.max(0) - pts.min(0)).max() / 2 + 2
        return float(best[0]), float(best[1]), float(np.clip(half, rmin, rmax))

    def chs(ids):
        c = sorted(set(int(chap[i]) + 1 for i in ids))
        return ("chapter " if len(c) == 1 else "chapters ") + ", ".join(map(str, c))
    feats = []          # (name, x, y, focus sentences, caption)
    for k, q in enumerate(kn[:2]):
        feats.append((f"Knot {'I' * (k + 1)}", q["x"], q["y"], q["sentences"],
                      f"{fmt(q['crossings'])} crossings among {len(q['sentences'])} sentences from {chs(q['sentences'])}."))
    hx, hy = mid(hb["i"], hb["i"])
    feats.append(("Hub", hx, hy, [hb["i"]],
                  f"{sref(hb['i'])}, crossed by {hb['crossings']} other sentences."))
    feats.append(("Return", rt["x"], rt["y"], [rt["i"], rt["j"]],
                  f"{sref(rt['i'])} crosses {sref(rt['j'])}, {fmt(rt['gap'])} sentences later."))
    cx_, cy_ = mid(co["first"], co["last"])
    feats.append(("Coil", cx_, cy_, list(range(co["first"], co["last"] + 1)),
                  f"{sref(co['first'])}–{co['last'] + 1}: {abs(co['quarter_turns'])} quarter turns "
                  f"{N_dir(co)} in twelve sentences."))
    dx_, dy_ = mid(dk["first"], dk["last"])
    feats.append(("Darkest", dx_, dy_, list(range(dk["first"], dk["last"] + 1)),
                  f"{sref(dk['first'])}–{dk['last'] + 1}: the thirty coldest sentences in a row."))
    kx, ky = mid(cor["first"], cor["last"])
    feats.append(("Corridor", kx, ky, list(range(cor["first"], cor["last"] + 1)),
                  f"{sref(cor['first'])}–{cor['last'] + 1}: {cor['sentences']} plain sentences, "
                  f"{fmt(cor['words'])} words in a straight line."))
    if pal is not None:
        feats.append(("Palimpsest", (pal[3] + pal[5]) / 2, (pal[4] + pal[6]) / 2, [int(pal[0]), int(pal[1])],
                      f"{sref(pal[1])} drawn over {sref(pal[0])} for {int(pal[2])} words."))
    windows = []
    for name, x, y, focus, cap in feats:
        if name.startswith(("Coil", "Darkest", "Corridor", "Palimpsest")):
            windows.append(focus_window(focus))
        else:
            windows.append((float(x), float(y), cfg.get("cutout_radius", 9.0)))
    letters_ = "ABCDEFGHIJ"
    anchors = [dict(x=v[0][0], y=v[0][1], key="start", lines=1, text="\\lblhead{Start}"),
               dict(x=v[-1][0], y=v[-1][1], key="end", lines=1, text="\\lblhead{End}")]
    for k, (name, x, y, _, _) in enumerate(feats):
        anchors.append(dict(x=x, y=y, key=letters_[k], lines=1,
                            text=f"\\lblletter{{{letters_[k]}}}\\,{name}"))
    band = cfg.get("label_band_mm", 22)
    labels = []
    draw.draw_maze(w, os.path.join(out, "maze.pdf"), TEXT_W, MAZE_H, band=band, anchors=anchors,
                   labels_out=labels, label_h=3.0)
    with open(os.path.join(out, "maze-labels.tex"), "w") as f:
        f.write("% generated: label positions in mm from the top-left of maze.pdf\n")
        for a in labels:
            anc = "north east" if a["side"] == "L" else "north west"
            x = a["lx"] - 0.8 if a["side"] == "L" else a["lx"] + 0.8
            al = "right" if a["side"] == "L" else "left"
            f.write(f"\\node[mazelabel,anchor={anc},align={al},text width={band - 2.5:.1f}mm] "
                    f"at ({x:.2f}mm,{-a['top']:.2f}mm) {{{a['text']}}};\n")
    # cut-outs: four to a page, each a magnified window with the sentences written along the path
    texts = [s_.text for s_ in S]
    CW, CH = 56.0, 60.0
    with open(os.path.join(out, "cutouts.tex"), "w") as f:
        f.write("% generated: magnified cut-outs of the labelled places\n")
        for k, (name, x, y, focus, cap) in enumerate(feats):
            L_ = letters_[k]
            wx, wy, wr = windows[k]
            draw.draw_cutout(w, texts, os.path.join(out, f"cut-{L_}.pdf"), CW, CH, wx, wy, wr, focus=focus)
            if k and k % 4 == 0:
                f.write("\\clearpage\n")
            f.write(f"\\begin{{minipage}}[t]{{{CW}mm}}\\includegraphics{{cut-{L_}.pdf}}\\par\\smallskip"
                    f"{{\\figfont\\footnotesize\\lblletter{{{L_}}}\\,\\textsc{{\\MakeLowercase{{{name}}}}}. {cap}}}"
                    f"\\end{{minipage}}")
            f.write("\\hfill\n" if k % 2 == 0 else "\\par\\vspace{5mm}\n")

    # ---- zoom on the knots: chapters told apart by dash pattern
    styles_order = [None, [1.2, 0.6], [0.25, 0.5]]
    for k, q in enumerate(kn[:2]):
        key = "AB"[k]
        top = sorted(q["composition"], key=lambda c: -q["composition"][c])[:3]
        styles = {c - 1: styles_order[r] for r, c in enumerate(top)}
        styles["other"] = [0.1, 0.9]
        R = cfg.get("zoom_radius", 45)
        draw.draw_zoom(w, os.path.join(out, f"zoom-{key}.pdf"), 120, 92, q["x"], q["y"], R,
                       chap, styles, crossings=cr)
        legend = ["solid", "dashed", "dotted"]
        N[f"knot{key}-legend"] = "; ".join(f"{legend[r]}: chapter {c} ({q['composition'][c]} sentences)"
                                           for r, c in enumerate(top)) + "; fine dots: other chapters"
        N[f"knot{key}-radius"] = fmt(R)

    # ---- mineshaft
    v3, pitch = walk.walk3d(n, t, cfg.get("shaft_delta", 0.75))
    marks = list(book.chapter_starts) + [len(S)]
    mpos, vscale = draw.draw_mineshaft(v3, os.path.join(out, "mineshaft.pdf"), TEXT_W, 118,
                                       azimuth=cfg.get("shaft_azimuth", 35),
                                       elevation=cfg.get("shaft_elevation", 14), marks=marks)
    if drop:
        draw.draw_mineshaft(v3r, os.path.join(out, "mineshaft-r.pdf"), 58, 100,
                            azimuth=cfg.get("shaft_azimuth", 35), elevation=cfg.get("shaft_elevation", 14),
                            vertical_scale=vscale, marks=marks)
        draw.draw_mineshaft(v3, os.path.join(out, "mineshaft-half.pdf"), 58, 100,
                            azimuth=cfg.get("shaft_azimuth", 35), elevation=cfg.get("shaft_elevation", 14),
                            vertical_scale=vscale, marks=marks)
    with open(os.path.join(out, "mineshaft-labels.tex"), "w") as f:
        for k, (x, y) in enumerate(mpos):
            lab = str(k + 1) if k < len(book.chapter_starts) else "end"
            f.write(f"\\node[shaftlabel] at ({x + 1.4:.2f}mm,{-y:.2f}mm) {{{lab}}};\n")
    N["shaft-vscale"] = f"1\\,:\\,{1 / vscale:.0f}" if vscale < 1 else "1\\,:\\,1"
    N["shaft-delta"] = fmt(cfg.get("shaft_delta", 0.75), 2)
    N["shaft-depth"] = fmt(float(-v3[:, 2].min()), 0); N["shaft-rise"] = fmt(float(v3[:, 2].max()), 0)
    N["shaft-final-pitch"] = fmt(float(pitch[-1]), 1)
    N["shaft-final"] = fmt(float(v3[-1, 2]), 0)
    N["shaft-min-pitch"] = fmt(float(pitch.min()), 1); N["shaft-max-pitch"] = fmt(float(pitch.max()), 1)
    kmin = int(np.argmin(v3[1:, 2]))
    N["shaft-deepest"] = sref(kmin); N["shaft-deepest-ch"] = str(ch(kmin))
    N["shaft-deepest-quote"] = quote(S[kmin].text)

    # ---- timeline (positions as fractions of the book)
    pos = lambda i: f"{i / len(S):.4f}"
    N["tl-chapters"] = ",".join(pos(i) for i in book.chapter_starts[1:])
    N["tl-knotA"] = f"{pos(kn[0]['first'])}/{pos(kn[0]['last'])}"
    N["tl-hub"] = pos(hb["i"]); N["tl-coil"] = pos(co["first"]); N["tl-dark"] = pos(dk["first"])
    N["tl-cor"] = pos(cor["first"]); N["tl-ret-i"] = pos(rt["i"]); N["tl-ret-j"] = pos(rt["j"])
    N["tl-shaft"] = pos(kmin)
    knot_sent = np.array(kn[0]["sentences"])
    hist, _ = np.histogram(knot_sent / len(S), bins=40, range=(0, 1))
    with open(os.path.join(out, "knot-time.dat"), "w") as f:
        f.write("x y\n")
        for k_, c in enumerate(hist):
            f.write(f"{(k_ + 0.5) / 40:.4f} {c}\n")

