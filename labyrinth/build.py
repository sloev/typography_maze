"""Build one book: text -> walk -> analysis -> figures + numbers for LaTeX.

    python3 -m labyrinth.build books/the-trial.yaml

Outputs in build/<slug>/:
    maze.pdf, maze-labels.tex      the whole book on one page, with labelled anchors
    zoom-<k>.pdf, zoom-<k>.tex     knot windows
    mineshaft.pdf                  the 3D walk
    numbers.tex                    every number used in the text, as macros
    baseline-<measure>.dat         shuffle distributions (pgfplots)
    gyration.dat                   radius of gyration over narrative time, with baseline band
    analysis.json                  everything, machine-readable
"""
